# op: 3 = поворотное со створкой, 4 = глухое. Ячейки настраиваем при габарите 1500x1500 (начальные центры), затем меняем размеры.
function Run($tpl, $name, $ops, $centers, $W, $H) {
  NewWindow $tpl
  for ($i=0; $i -lt $ops.Count; $i++) { Configure 'none' $ops[$i] $false $false $false $centers[$i] }
  Measure-Grid $name $W $H $out
}
